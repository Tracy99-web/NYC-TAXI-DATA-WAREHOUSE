-- ==========================================================================================================
-- Builds the analytics layer using a star schema.
-- Creates dimension tables for dates, zones, payment type and a fact table containing validated taxi trips.
-- ============================================================================================================

USE SCHEMA NYC_TAXI_DB.ANALYTICS;


CREATE OR REPLACE TABLE DIM_ZONE AS

SELECT
    LOCATION_ID,
    BOROUGH,
    ZONE,
    SERVICE_ZONE

FROM NYC_TAXI_DB.RAW.RAW_TAXI_ZONES;

SELECT *
FROM DIM_ZONE
LIMIT 10;

SELECT COUNT(*)
FROM DIM_ZONE;

CREATE OR REPLACE TABLE DIM_PAYMENT_TYPE (
    PAYMENT_TYPE_ID INTEGER,
    PAYMENT_TYPE_DESCRIPTION VARCHAR
);

INSERT INTO DIM_PAYMENT_TYPE
VALUES
    (1, 'Credit card'),
    (2, 'Cash'),
    (3, 'No charge'),
    (4, 'Dispute'),
    (5, 'Unknown'),
    (6, 'Voided trip');

SELECT *
FROM DIM_PAYMENT_TYPE;

CREATE OR REPLACE TABLE DIM_DATE AS

SELECT DISTINCT
    TO_DATE(PICKUP_DATETIME) AS DATE_KEY,

    YEAR(PICKUP_DATETIME) AS YEAR,

    MONTH(PICKUP_DATETIME) AS MONTH_NUMBER,

    MONTHNAME(PICKUP_DATETIME) AS MONTH_NAME,

    DAY(PICKUP_DATETIME) AS DAY_OF_MONTH,

    DAYOFWEEK(PICKUP_DATETIME) AS DAY_OF_WEEK_NUMBER,

    DAYNAME(PICKUP_DATETIME) AS DAY_NAME

FROM NYC_TAXI_DB.STAGING.STG_TAXI_TRIPS

WHERE IS_OUT_OF_PERIOD = FALSE;

SELECT *
FROM DIM_DATE
ORDER BY DATE_KEY
LIMIT 10;

CREATE OR REPLACE TABLE FACT_TRIPS AS

SELECT
    ROW_NUMBER() OVER (
        ORDER BY PICKUP_DATETIME, DROPOFF_DATETIME
    ) AS TRIP_ID,

    TO_DATE(PICKUP_DATETIME) AS DATE_KEY,

    PU_LOCATION_ID AS PICKUP_LOCATION_ID,
    DO_LOCATION_ID AS DROPOFF_LOCATION_ID,

    PAYMENT_TYPE AS PAYMENT_TYPE_ID,

    VENDOR_ID,

    PICKUP_DATETIME,
    DROPOFF_DATETIME,

    PASSENGER_COUNT,
    TRIP_DISTANCE,
    TRIP_DURATION_MINUTES,

    FARE_AMOUNT,
    EXTRA,
    MTA_TAX,
    TIP_AMOUNT,
    TOLLS_AMOUNT,
    IMPROVEMENT_SURCHARGE,
    TOTAL_AMOUNT,
    CONGESTION_SURCHARGE,

    SOURCE_FILE,
    LOAD_TIMESTAMP

FROM NYC_TAXI_DB.STAGING.STG_TAXI_TRIPS

WHERE QUALITY_STATUS = 'VALID';


