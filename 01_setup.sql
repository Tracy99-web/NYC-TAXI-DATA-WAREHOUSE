-- ======================================================================================
-- Project setup: Database, Schema and Warehouse creation
-- ======================================================================================

CREATE DATABASE NYC_TAXI_DB;

CREATE SCHEMA NYC_TAXI_DB.RAW;

CREATE SCHEMA NYC_TAXI_DB.STAGING;

CREATE SCHEMA NYC_TAXI_DB.ANALYTICS;

CREATE WAREHOUSE NYC_TAXI_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE NYC_TAXI_WH;
USE DATABASE NYC_TAXI_DB;

USE SCHEMA RAW;

CREATE TABLE RAW_TAXI_ZONES (
    LOCATION_ID INTEGER,
    BOROUGH VARCHAR,
    ZONE VARCHAR,
    SERVICE_ZONE VARCHAR
);


CREATE OR REPLACE TABLE RAW_TAXI_TRIPS (
    VENDOR_ID INTEGER,
    PICKUP_DATETIME TIMESTAMP_NTZ,
    DROPOFF_DATETIME TIMESTAMP_NTZ,
    PASSENGER_COUNT INTEGER,
    TRIP_DISTANCE FLOAT,
    RATE_CODE_ID INTEGER,
    STORE_AND_FWD_FLAG VARCHAR,
    PU_LOCATION_ID INTEGER,
    DO_LOCATION_ID INTEGER,
    PAYMENT_TYPE INTEGER,
    FARE_AMOUNT FLOAT,
    EXTRA FLOAT,
    MTA_TAX FLOAT,
    TIP_AMOUNT FLOAT,
    TOLLS_AMOUNT FLOAT,
    IMPROVEMENT_SURCHARGE FLOAT,
    TOTAL_AMOUNT FLOAT,
    CONGESTION_SURCHARGE FLOAT,

    SOURCE_FILE VARCHAR,
    LOAD_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


USE DATABASE NYC_TAXI_DB;
USE SCHEMA RAW;
USE WAREHOUSE NYC_TAXI_WH;

CREATE OR REPLACE FILE FORMAT NYC_TAXI_CSV_FORMAT
TYPE = CSV
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
SKIP_HEADER = 1
NULL_IF = ('', 'NULL', 'null')
EMPTY_FIELD_AS_NULL = TRUE;
CREATE OR REPLACE STAGE NYC_TAXI_STAGE
FILE_FORMAT = NYC_TAXI_CSV_FORMAT;

SHOW STAGES;


