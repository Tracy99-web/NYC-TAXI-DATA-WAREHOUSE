-- ======================================================================================
-- Profiling source data and identifying records that violate expected
-- temporal, geographic and financial constraints.
-- ======================================================================================
SELECT
    YEAR(PICKUP_DATETIME) AS YEAR,
    COUNT(*) AS ROW_COUNT
FROM RAW_TAXI_TRIPS
GROUP BY YEAR(PICKUP_DATETIME)
ORDER BY YEAR(PICKUP_DATETIME);

SELECT
    YEAR(PICKUP_DATETIME) AS PICKUP_YEAR,
    MONTH(PICKUP_DATETIME) AS PICKUP_MONTH,
    COUNT(*) AS ROW_COUNT
FROM RAW_TAXI_TRIPS
GROUP BY
    YEAR(PICKUP_DATETIME),
    MONTH(PICKUP_DATETIME)
ORDER BY
    PICKUP_YEAR,
    PICKUP_MONTH;


SELECT
    COUNT(*) AS ZERO_OR_NEGATIVE_DISTANCE
FROM RAW_TAXI_TRIPS
WHERE TRIP_DISTANCE <= 0;

SELECT
    COUNT(*) AS NEGATIVE_FARES
FROM RAW_TAXI_TRIPS
WHERE FARE_AMOUNT < 0;

SELECT
    COUNT(*) AS NEGATIVE_TOTALS
FROM RAW_TAXI_TRIPS
WHERE TOTAL_AMOUNT < 0;

SELECT
    COUNT(*) AS INVALID_PICKUP_LOCATIONS
FROM RAW_TAXI_TRIPS T
LEFT JOIN RAW_TAXI_ZONES Z
    ON T.PU_LOCATION_ID = Z.LOCATION_ID
WHERE Z.LOCATION_ID IS NULL;

SELECT
    COUNT(*) AS INVALID_DROPOFF_LOCATIONS
FROM RAW_TAXI_TRIPS T
LEFT JOIN RAW_TAXI_ZONES Z
    ON T.DO_LOCATION_ID = Z.LOCATION_ID
WHERE Z.LOCATION_ID IS NULL;

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        PICKUP_DATETIME < '2019-01-01'
        OR PICKUP_DATETIME >= '2019-02-01'
    ) AS OUT_OF_MONTH,

    COUNT_IF(
        TRIP_DISTANCE <= 0
    ) AS ZERO_OR_NEGATIVE_DISTANCE,

    COUNT_IF(
        DROPOFF_DATETIME < PICKUP_DATETIME
    ) AS DROPOFF_BEFORE_PICKUP,

    COUNT_IF(
        DROPOFF_DATETIME = PICKUP_DATETIME
    ) AS ZERO_DURATION,

    COUNT_IF(
        FARE_AMOUNT < 0
    ) AS NEGATIVE_FARE,

    COUNT_IF(
        TOTAL_AMOUNT < 0
    ) AS NEGATIVE_TOTAL,
    
    COUNT_IF(FARE_AMOUNT < 0 AND TOTAL_AMOUNT < 0
    ) AS BOTH_NEGATIVE,
    
    COUNT_IF(FARE_AMOUNT < 0 AND TOTAL_AMOUNT >= 0
    ) AS FARE_ONLY_NEGATIVE,
    
    COUNT_IF(TOTAL_AMOUNT < 0 AND FARE_AMOUNT >= 0
    ) AS TOTAL_ONLY_NEGATIVE
    
FROM NYC_TAXI_DB.RAW.RAW_TAXI_TRIPS;
